"""Export the paper's Fig. 1 data for the static RoboElo project page."""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd


SITE = Path(__file__).resolve().parents[1]
RESEARCH = SITE.parent / "RoboElo"
sys.path[:0] = [str(RESEARCH), str(RESEARCH / "scripts"), str(SITE.parent / "RoboElo_paper_figures_all")]

import make_fig1_options as figure


def interval(lo, hi):
    return None if pd.isna(lo) or pd.isna(hi) else [lo, hi]


def export():
    # Since 2026-11-25 the paper's Fig. 1 has two periods split at G0.5 (make_fig1_options.py E2, scheme "g05");
    # until then three eras (fig1_eras_numbers.json, option E).
    figure.set_scheme("g05")
    metadata = json.loads((RESEARCH / "figures/fig1_g05_numbers.json").read_text(encoding="utf-8"))
    ratings = figure.P.MF.rated().dropna(subset=["year"])
    records = {policy for policy, _, _ in metadata["records"]}
    release_rows = pd.read_csv(RESEARCH / "data/policy_release_dates.csv")
    release_dates = {}
    for row in release_rows.itertuples():
        date = next((value for value in (row.date, row.paper_first_public, row.weights_public)
                     if pd.notna(value)), None)
        if date is not None:
            release_dates[row.policy.lower()] = date
    tests = pd.read_csv(RESEARCH / "results/unified/test_difficulty.csv")
    policies = []
    for row in ratings.sort_values("year", kind="stable").itertuples():
        release_id = "octo" if row.policy.lower() == "octo_small" else row.policy.lower()
        policies.append(dict(id=row.policy, name=figure.nm(row.policy), year=row.year, date=release_dates[release_id],
                             elo=row.general_elo, interval=interval(row.general_lo, row.general_hi),
                             kind=figure.kind(row.policy), record=row.policy in records,
                             benchmarks=[name.strip().replace("RoboTwin", "RoboTwin 2.0")
                                         for name in row.benchmarks.split(",")]))

    benchmarks = []
    for name in figure.ORDER:
        values = tests.loc[tests.setting.isin(figure.UNITS[name]), "difficulty_elo"].to_numpy()
        grid = np.linspace(figure.B2_YLIM[0], figure.B2_YLIM[1] + 600, 900)
        density = figure.gaussian_kde(values, bw_method=0.4)(grid)
        width = density / density.max() * 0.17
        visible = np.flatnonzero(width > 0.03 * 0.17)
        indices = np.unique(np.r_[visible[0]:visible[-1] + 1:4, visible[-1]])
        side = {"RoboTwin clean": "left", "RoboTwin randomized": "right"}.get(name, "both")
        benchmarks.append(dict(id=name, name=name.replace("RoboTwin ", "RoboTwin 2.0 · "),
                               side=side, date=figure.P.BENCH_DAY[name], year=figure.P.bench_year(name),
                               count=len(values), median=float(np.median(values)),
                               quantiles=np.quantile(values, [0.1, 0.9]).tolist(),
                               density=[[round(grid[i], 2), round(width[i], 6)] for i in indices]))

    claude_sources = {name: (date, score) for name, date, score in figure.CLAUDE}
    claude = [dict(id=row["name"], name=row["name"], year=row["year"], elo=row["mu"],
                   kind="external", date=claude_sources[row["name"]][0],
                   benchmarkScore=claude_sources[row["name"]][1], benchmarkLevel=row["level"])
              for row in metadata["claude"]]

    assert len(policies) == 44 and sum(row["count"] for row in benchmarks) == 212
    assert {policy["id"] for policy in policies if policy["record"]} == records
    assert np.isclose(benchmarks[-1]["quantiles"][1], metadata["next_needed"][0])
    data = dict(policies=policies + claude, benchmarks=benchmarks,
                eras=dict(breaks=list(figure.ERA_BREAKS), rates=metadata["k"],
                          nodes=list(zip(*metadata["nodes"]))),
                forecast=dict(cutoff=figure.X_CUTOFF, x=metadata["x_end"], y=metadata["y_end"],
                              end=figure.X_CUTOFF + figure.YEARS + 0.1, pace=metadata["k"][-1],
                              tasks=[row[-1] for row in metadata["k_in"]],
                              tasksAndPolicies=[row[-1] for row in metadata["k_out"]],
                              crossing=metadata["t_need"], crossingInterval=metadata["t_need_range"],
                              needed=metadata["next_needed"]))
    (SITE / "assets/figure-data.js").write_text(
        "// Generated by scripts/export_figure.py from the paper data.\n"
        + "const figureData = " + json.dumps(data, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    export()
